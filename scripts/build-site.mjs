function legalPages() {
  const dir = path.join(ROOT, "content/legal");
  return fs.readdirSync(dir).filter((f) => f.endsWith(".html")).map((file) => {
    const src = fs.readFileSync(path.join(dir, file), "utf8");
    const meta = Object.fromEntries([...src.matchAll(/^\s*(title|description):\s*(.+)$/gm)].map((m) => [m[1], m[2].trim()]));
    const body = src.replace(/<!--[\s\S]*?-->\s*/, "");
    const draft = body.includes("[[");
    const slug = file.replace(/\.html$/, "");
    const url = `${SITE}${slug}.html`;
    const html = `${head({
      title: `${meta.title} — TravelOnBuddy`,
      description: meta.description,
      url,
      image: "img/boats.jpg",
      imageAlt: "Boats on the Ganga along the ghats of Varanasi",
      jsonLd: { "@context": "https://schema.org", ...breadcrumb([["Home", SITE], [meta.title, url]]) },
      noindex: draft,
    })}
  <body>
    <div class="page">
      <div id="site-header"></div>

      <main>
        <div
          id="page-header-slot"
          data-eyebrow="TravelOnBuddy"
          data-title="${esc(meta.title)}"
          data-image="img/boats.jpg"
          data-pos="center 46%"
        ></div>

        <section class="section">
          <div class="shell">
            <article class="prose">${draft ? `
              <p class="prose__draft" role="note">Draft — the highlighted details still need filling in before this page goes live.</p>` : ""}
              ${body.trim().replace(/\[\[([^\]]+)\]\]/g, "<mark>$1</mark>").replace(/\n/g, "\n              ")}
            </article>
          </div>
        </section>
      </main>
${tail}`;
    fs.writeFileSync(path.join(DOCS, `${slug}.html`), html);
    return { slug, draft };
  });
}

function sitemap() {
  const pages = [
    ["", "1.0", "weekly"],
    ["experiences.html", "0.9", "weekly"],
    ...experiences.map((x) => [`${x.slug}.html`, "0.8", "monthly"]),
    ["plan.html", "0.9", "monthly"],
    ["why-buddy.html", "0.7", "monthly"],
    ["buddies.html", "0.7", "weekly"],
    ["stories.html", "0.6", "weekly"],
    ["become-a-buddy.html", "0.6", "monthly"],
    ["privacy.html", "0.2", "yearly"],
    ["terms.html", "0.2", "yearly"],
    ["refund-policy.html", "0.3", "yearly"],
  ].filter(([p]) => p === "" || (fs.existsSync(path.join(DOCS, p)) && !/name="robots" content="noindex/.test(fs.readFileSync(path.join(DOCS, p), "utf8"))));
  const urls = pages
    .map(
      ([p, priority, freq]) =>
        `  <url>\n    <loc>${SITE}${p}</loc>\n    <lastmod>${config.lastmod}</lastmod>\n    <changefreq>${freq}</changefreq>\n    <priority>${priority}</priority>\n  </url>`,
    )
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

function syncCredits() {
  const used = new Set();
  for (const f of fs.readdirSync(DOCS).filter((f) => f.endsWith(".html")).map((f) => path.join(DOCS, f))
    .concat(fs.readdirSync(path.join(DOCS, "js")).map((f) => path.join(DOCS, "js", f)))
    .concat([path.join(DOCS, "experiences.json")])) {
    for (const m of fs.readFileSync(f, "utf8").matchAll(/img\/([a-z_]+)\.jpg/g)) used.add(m[1]);
  }
  const credits = JSON.parse(fs.readFileSync(path.join(DOCS, "credits.json"), "utf8"));
  const missing = [...used].filter((id) => !credits.some((c) => c.id === id));
  if (missing.length) throw new Error(`No entry in docs/credits.json for: ${missing.join(", ")}`);
  const j = (v) => JSON.stringify(v);
  const rows = credits
    .filter((c) => used.has(c.id))
    .map((c) => `  { id: ${j(c.id)}, title: ${j(c.title)}, creator: ${j(c.creator)}, license: ${j(c.license)}, source: ${j(c.source)} },`)
    .join("\n");
  const navPath = path.join(DOCS, "js/nav.js");
  const nav = fs.readFileSync(navPath, "utf8");
  const start = nav.indexOf("const CREDITS = [");
  const end = nav.indexOf("];", start) + 2;
  fs.writeFileSync(navPath, `${nav.slice(0, start)}const CREDITS = [\n${rows}\n];${nav.slice(end)}`);
  return used.size;
}

function syncApiBase() {
  const apiPath = path.join(DOCS, "js/api.js");
  const src = fs.readFileSync(apiPath, "utf8");
  const api = (config.api || "").replace(/\/$/, "");
  fs.writeFileSync(apiPath, src.replace(/const PRODUCTION_API = ".*?";/, `const PRODUCTION_API = ${JSON.stringify(api)};`));
}

