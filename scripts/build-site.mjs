// Generates the parts of the public site (docs/) that are driven by data:
//   - one page per experience in docs/experiences.json, plus experiences.html
//   - privacy.html, terms.html, refund-policy.html from content/legal/*.html
//     (while any [[placeholder]] is left, a page is marked draft and noindex)
//   - docs/sitemap.xml
//   - the photo-credits list in docs/js/nav.js (only photos the site uses)
//
// The site itself stays plain HTML with no build step: run this after editing
// experiences.json, scripts/site.config.json or adding a photo, then commit the
// output.   node scripts/build-site.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DOCS = path.join(ROOT, "docs");
const config = JSON.parse(fs.readFileSync(path.join(ROOT, "scripts/site.config.json"), "utf8"));
const SITE = config.url.endsWith("/") ? config.url : `${config.url}/`;
const experiences = JSON.parse(fs.readFileSync(path.join(DOCS, "experiences.json"), "utf8"));

const esc = (v) =>
  String(v ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const inr = (n) => `₹${Number(n).toLocaleString("en-IN")}`;
const priceText = (p) => (p ? `From ${inr(p.from)} ${p.per ? `per ${p.per}` : ""}`.trim() : "Price on request");

const TICK = `<svg viewBox="0 0 24 24" width="16" height="16" fill="none" stroke="currentColor" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><polyline points="20 6 9 17 4 12"/></svg>`;
const ARROW = `<svg viewBox="0 0 24 24" width="15" height="15" fill="none" stroke="currentColor" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><line x1="4" y1="12" x2="20" y2="12"/><polyline points="14 6 20 12 14 18"/></svg>`;
const PIN = `<svg viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M20 10c0 6-8 12-8 12s-8-6-8-12a8 8 0 0 1 16 0Z"/><circle cx="12" cy="10" r="3"/></svg>`;

function imageSize(rel) {
  // JPEG SOF marker scan — enough for og:image:width/height without a dependency.
  const buf = fs.readFileSync(path.join(DOCS, rel));
  for (let i = 2; i < buf.length; ) {
    const marker = buf[i + 1];
    const len = buf.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xc3) return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
    i += 2 + len;
  }
  return null;
}

